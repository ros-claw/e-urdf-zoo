from __future__ import annotations

import json
import sys
from pathlib import Path


def print_banner(title: str, width: int = 70) -> None:
    """Print a fancy banner."""
    print("=" * width)
    print(f"  {title}")
    print("=" * width)
    print()


def print_step(step_num: int, title: str) -> None:
    """Print a step header."""
    print(f"\n{'─' * 70}")
    print(f"🚀 STEP {step_num}: {title}")
    print("─" * 70)


def demo_step_1_sdk_to_mcp() -> Path:
    """Step 1: Use sdk_to_mcp (Spear) to convert robot SDK to MCP Asset Bundle.

    This demonstrates the Self-Healing Generator creating a valid MCP server
    from a hypothetical robot SDK.
    """
    print_step(1, "SPEAR ACTIVATED - sdk_to_mcp generates Asset Bundle")

    # Import sdk_to_mcp modules
    sys.path.insert(0, str(Path(__file__).parent.parent / "sdk_to_mcp"))

    from sdk_to_mcp_core import (
        CommunicationProtocol,
        SDKMetadata,
        SDKToMCPTransformer,
    )

    # Create hypothetical robot SDK metadata
    metadata = SDKMetadata(
        name="demo_robot_arm",
        version="1.0.0",
        protocol=CommunicationProtocol.ROS2,
        source_url="https://github.com/example/demo_robot_sdk",
        doc_url="https://docs.example.com/demo_robot",
        hardware_models=["DR-100"],
    )

    print(f"📝 SDK: {metadata.name} v{metadata.version}")
    print(f"🔌 Protocol: {metadata.protocol.name}")
    print(f"🤖 Hardware: {', '.join(metadata.hardware_models)}")
    print()

    # Mock LLM generator for demo purposes
    def mock_llm_generator(prompt: str) -> str:
        """Generate a simple MCP server for demo."""
        return '''"""
Demo Robot Arm MCP Server
Auto-generated by sdk_to_mcp Self-Healing Generator
"""
from mcp.server.fastmcp import FastMCP
import numpy as np

mcp = FastMCP("demo-robot-arm")

@mcp.tool()
def move_joint(joint_id: int, position: float, velocity: float = 0.5) -> str:
    """Move a single joint to target position."""
    # Validate inputs
    if not 0 <= joint_id <= 5:
        return f"Error: joint_id {joint_id} out of range [0, 5]"
    if not -3.14 <= position <= 3.14:
        return f"Error: position {position} out of range [-3.14, 3.14]"
    return f"Moving joint {joint_id} to {position:.2f} rad"

@mcp.tool()
def get_joint_states() -> str:
    """Get current joint positions."""
    return "Joint states: [0.0, -0.5, 1.2, 0.0, 0.5, 0.0]"

@mcp.tool()
def move_to_pose(x: float, y: float, z: float, roll: float = 0.0, pitch: float = 0.0, yaw: float = 0.0) -> str:
    """Move end-effector to target pose using IK."""
    return f"Moving to pose: ({x}, {y}, {z}, {roll}, {pitch}, {yaw})"

def main():
    mcp.run()

if __name__ == "__main__":
    main()
'''

    # Transform SDK with Self-Healing
    transformer = SDKToMCPTransformer()

    # For demo, we'll create the output directory directly
    output_dir = Path(__file__).parent / "demo_output"
    output_dir.mkdir(exist_ok=True)

    print("🔧 Running Self-Healing Generator...")
    print("   - Generating MCP server code")
    print("   - Testing syntax and imports")
    print("   - Creating Asset Bundle")
    print()

    # Generate server code
    result = transformer.transform_sdk_with_self_healing(
        metadata=metadata,
        sdk_path=Path(__file__).parent,  # Dummy SDK path
        output_path=output_dir,
        llm_generator=mock_llm_generator,
        max_attempts=3,
    )

    bundle = result["bundle"]

    print("✅ Asset Bundle generated!")
    print(f"   📦 Robot ID: {bundle.robot_id}")
    print(f"   🤖 Name: {bundle.robot_name}")
    print(f"   📝 Files created: {len(result['files'])}")
    for name, path in result["files"].items():
        print(f"      • {name}")

    print()
    print("📄 Generated server.py preview:")
    print("─" * 50)
    code_preview = "\n".join(bundle.server_code.split("\n")[:15])
    print(code_preview)
    print("...")
    print("─" * 50)

    return output_dir


def demo_step_2_load_in_firewall(bundle_dir: Path) -> None:
    """Step 2: Load the generated embodiment in mjlab-mcp-server (Shield).

    This demonstrates how the physics firewall loads the Asset Bundle
    and prepares for safety validation.
    """
    print_step(2, "SHIELD ACTIVATED - mjlab-mcp-server loads embodiment")

    # Load the e_urdf.json from the bundle
    e_urdf_path = bundle_dir / "e_urdf.json"
    if e_urdf_path.exists():
        config = json.loads(e_urdf_path.read_text())
        print("📋 Loaded e_urdf.json:")
        print(f"   🔖 Embodiment ID: {config.get('embodiment_id')}")
        print(f"   📛 Name: {config.get('embodiment_name')}")
        print(f"   ⚙️  DOF: {config.get('kinematics', {}).get('dof')}")
        print(f"   🛡️  Validation: {config.get('physical_firewall', {}).get('validation_level')}")
    else:
        print("⚠️  e_urdf.json not found, using defaults")

    print()
    print("🔧 Initializing Physics Sandbox...")
    print("   - Loading MuJoCo model")
    print("   - Applying safety constraints")
    print("   - Initializing Semantic Translator")
    print()

    # Note: We can't actually run MuJoCo without the model file,
    # so we show what would happen
    print("✅ Physics Firewall Ready!")
    print("   🎯 Can validate trajectories")
    print("   🗣️  Semantic error translation enabled")
    print("   ⚡ GPU batch validation available")


